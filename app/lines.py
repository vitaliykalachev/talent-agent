"""Строки резюме — одна нумерация для разбора, оценки и «Показать в резюме».

CRM часто выгружает резюме одной строкой в сотни знаков. Модель ссылается на номера
строк, а в одной огромной строке ей не на что опереться: она промахивается на соседнюю
строку с [ИМЯ], и проверка кода отбрасывает все доводы. Поэтому строки длиннее LONG
знаков делятся на фрагменты: по концам фраз, после «;», перед « • », « — » и « - »
между словами, а фрагменты длиннее PIECE — ещё и после запятых.

Пробел на границе меняется на перенос, длина текста не меняется: смещения символов
совпадают с оригиналом, поэтому подсветка «Показать в резюме» ложится на исходник.
Деление идёт до обезличивания, а оно сохраняет число строк, так что модель и экран
нумеруют одинаково.
"""

import re

LONG = 200  # знаков: строку длиннее делим на фрагменты
PIECE = 100  # фрагмент длиннее и после деления по фразам делим ещё по запятым
STRONG_RE = re.compile(
    # конец фразы: три буквы или цифра перед точкой и заглавная после — не «г. Москва»,
    # не инициалы «И. И.», не «50 тыс. руб.»
    r"(?:(?<=[^\W\d_]{3}[.!?])|(?<=[\d%»\")][.!?]))\s(?=[«\"(]?[A-ZА-ЯЁ0-9])"
    r"|(?<=;)\s(?=\S)"
    r"|\s(?=•\s)"  # перед пунктом списка « • »
    # перед « — » между словами — не в «2019 — по настоящее время»
    r"|(?:(?<=[^\W\d_])|(?<=[»\")]))\s(?=[—–]\s)"
    r"|(?<=[^\W\d_])\s(?=-\s[^\W\d_])"  # перед « - » между словами
)
COMMA_RE = re.compile(r"(?<=,)\s(?=\S)")


def resume_lines(text: str) -> str:
    """Текст резюме, в котором длинные строки разбиты на фрагменты; той же длины."""
    out = []
    for line in (text or "").split("\n"):
        if len(line) > LONG:
            pieces = STRONG_RE.sub("\n", line).split("\n")
            line = "\n".join(COMMA_RE.sub("\n", p) if len(p) > PIECE else p for p in pieces)
        out.append(line)
    return "\n".join(out)
